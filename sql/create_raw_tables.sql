CREATE TABLE IF NOT EXISTS RAW_CHANNELS (
    CHANNEL_ID VARCHAR,
    TITLE VARCHAR,
    DESCRIPTION VARCHAR,
    COUNTRY VARCHAR,
    PUBLISHED_AT VARCHAR,
    SUBSCRIBER_COUNT NUMBER,
    HIDDEN_SUBSCRIBER_COUNT BOOLEAN,
    VIEW_COUNT NUMBER,
    VIDEO_COUNT NUMBER,
    UPLOADS_PLAYLIST_ID VARCHAR,
    SNAPSHOT_DATE DATE,
    LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS RAW_VIDEOS (
    VIDEO_ID VARCHAR,
    CHANNEL_ID VARCHAR,
    TITLE VARCHAR,
    DESCRIPTION VARCHAR,
    PUBLISHED_AT VARCHAR,
    DURATION VARCHAR,
    CATEGORY_ID VARCHAR,
    TAGS VARCHAR,
    VIEW_COUNT NUMBER,
    LIKE_COUNT NUMBER,
    COMMENT_COUNT NUMBER,
    SNAPSHOT_DATE DATE,
    LOADED_AT TIMESTAMP_NTZ
);